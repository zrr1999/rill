private actor PasteboardImageWorkerGate {
    struct Statistics: Sendable {
        let invocationCount: Int
        let maximumConcurrentWorkerCount: Int
    }

    private var invocationCount = 0
    private var activeWorkerCount = 0
    private var maximumConcurrentWorkerCount = 0
    private var releasePermitCount = 0
    private var releasesAllWorkers = false
    private var workerContinuations: [CheckedContinuation<Void, Never>] = []
    private var invocationWaiters: [(
        count: Int,
        continuation: CheckedContinuation<Void, Never>
    )] = []

    func blockWorker() async {
        invocationCount += 1
        activeWorkerCount += 1
        maximumConcurrentWorkerCount = max(
            maximumConcurrentWorkerCount,
            activeWorkerCount
        )
        resumeSatisfiedInvocationWaiters()

        if releasesAllWorkers {
            activeWorkerCount -= 1
            return
        }
        if releasePermitCount > 0 {
            releasePermitCount -= 1
            activeWorkerCount -= 1
            return
        }
        await withCheckedContinuation { continuation in
            workerContinuations.append(continuation)
        }
        activeWorkerCount -= 1
    }

    func waitUntilBlocked() async {
        await waitUntilInvocationCount(1)
    }

    func waitUntilInvocationCount(_ count: Int) async {
        guard invocationCount < count else { return }
        await withCheckedContinuation { continuation in
            invocationWaiters.append((count, continuation))
        }
    }

    func releaseWorker() {
        releaseNextWorker()
    }

    func releaseNextWorker() {
        guard !workerContinuations.isEmpty else {
            releasePermitCount += 1
            return
        }
        workerContinuations.removeFirst().resume()
    }

    func releaseAllWorkers() {
        releasesAllWorkers = true
        let continuations = workerContinuations
        workerContinuations.removeAll()
        continuations.forEach { $0.resume() }
    }

    func statistics() -> Statistics {
        Statistics(
            invocationCount: invocationCount,
            maximumConcurrentWorkerCount: maximumConcurrentWorkerCount
        )
    }

    private func resumeSatisfiedInvocationWaiters() {
        var pending: [(
            count: Int,
            continuation: CheckedContinuation<Void, Never>
        )] = []
        for waiter in invocationWaiters {
            if invocationCount >= waiter.count {
                waiter.continuation.resume()
            } else {
                pending.append(waiter)
            }
        }
        invocationWaiters = pending
    }
}
