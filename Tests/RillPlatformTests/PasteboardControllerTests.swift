    func testConcurrentImageReadsForSameChangeCountShareOneWorker() async throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        let pngData = try makePNGData()
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.setData(pngData, forType: .png))
        let expectedChangeCount = pasteboard.changeCount
        let workerGate = PasteboardImageWorkerGate()
        let controller = SystemClipboardPort(
            pasteboard: pasteboard,
            imageProcessingGate: {
                await workerGate.blockWorker()
            }
        )

        let firstRead = Task {
            await controller.readSnapshot(ifChangeCountIs: expectedChangeCount)
        }
        await workerGate.waitUntilInvocationCount(1)
        let secondRead = Task {
            await controller.readSnapshot(ifChangeCountIs: expectedChangeCount)
        }
        for _ in 0 ..< 20 {
            await Task.yield()
        }
        await workerGate.releaseAllWorkers()

        let firstReadValue = await firstRead.value
        let secondReadValue = await secondRead.value
        let firstSnapshot = try XCTUnwrap(firstReadValue)
        let secondSnapshot = try XCTUnwrap(secondReadValue)
        let statistics = await workerGate.statistics()
        XCTAssertEqual(firstSnapshot.imagePNGData, pngData)
        XCTAssertEqual(secondSnapshot.imagePNGData, pngData)
        XCTAssertEqual(statistics.invocationCount, 1)
        XCTAssertEqual(statistics.maximumConcurrentWorkerCount, 1)
    }

    func testChangedImageWaitsForOldWorkerAndDiscardsOldResult() async throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        let oldPNGData = try makeImageData(using: .png, width: 2, height: 2)
        let newPNGData = try makeImageData(using: .png, width: 3, height: 2)
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.setData(oldPNGData, forType: .png))
        let oldChangeCount = pasteboard.changeCount
        let workerGate = PasteboardImageWorkerGate()
        let controller = SystemClipboardPort(
            pasteboard: pasteboard,
            imageProcessingGate: {
                await workerGate.blockWorker()
            }
        )

        let oldRead = Task {
            await controller.readSnapshot(ifChangeCountIs: oldChangeCount)
        }
        await workerGate.waitUntilInvocationCount(1)

        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.setData(newPNGData, forType: .png))
        let newChangeCount = pasteboard.changeCount
        let newRead = Task {
            await controller.readSnapshot(ifChangeCountIs: newChangeCount)
        }
        for _ in 0 ..< 20 {
            await Task.yield()
        }

        await workerGate.releaseNextWorker()
        let oldReadValue = await oldRead.value
        XCTAssertNil(oldReadValue)
        await workerGate.waitUntilInvocationCount(2)
        await workerGate.releaseNextWorker()

        let newReadValue = await newRead.value
        let newSnapshot = try XCTUnwrap(newReadValue)
        let newSnapshotData = try XCTUnwrap(newSnapshot.imagePNGData)
        let statistics = await workerGate.statistics()
        XCTAssertEqual(NSBitmapImageRep(data: newSnapshotData)?.pixelsWide, 3)
        XCTAssertEqual(newSnapshot.changeCount, newChangeCount)
        XCTAssertEqual(statistics.invocationCount, 2)
        XCTAssertEqual(statistics.maximumConcurrentWorkerCount, 1)
    }

